#!/usr/bin/env -S uv run --quiet python
"""
Generate lib/src/catalog.g.dart, the bundled model catalogue, from
transcribe.cpp's own catalog/ at the engine tag this package ships.

Why the engine tag and not upstream main: the catalogue moves faster than our
releases, and a newer entry can name a family the linked engine cannot load
(granite5_ctc is in 0.3.1 and not in 0.2.2). Generated from the same tag as
the xcframework, every bundled entry loads by construction.

What it keeps:
  * transcribe-capable models with a published GGUF repo;
  * files of at most 1 GB (MAX_BYTES). Larger files exist, but a phone that
    can hold one in memory next to an app is not one we can test on.

What it adds that upstream's catalogue does not carry:
  * SHA-256 per file, from the Hugging Face API (the LFS object id). The
    model manager verifies it before the `.part` rename that installs a file;
    without it a truncated or corrupted download looks installed.
  * The Hugging Face commit, so the URL is `resolve/<commit>/<file>` rather
    than `resolve/main/<file>`. A republished file under `main` would no longer
    match its hash, and every install of that model would fail.

A file whose size no longer matches the catalogue was republished after the
tag and is skipped. A repo committed to after the tag is reported either way:
its files may have been converted by a newer engine than the one we link.

Usage:
    tool/gen_catalog.py ../transcribe.cpp v0.3.1 -o lib/src/catalog.g.dart
"""

import argparse
import json
import subprocess
import sys
import urllib.request
from datetime import datetime

MAX_BYTES = 1_000_000_000
HF = "https://huggingface.co"


def git(repo, *args):
    return subprocess.run(
        ["git", "-C", repo, *args], check=True, capture_output=True, text=True
    ).stdout


def hf(path):
    with urllib.request.urlopen(f"{HF}/api/{path}", timeout=30) as r:
        return json.load(r)


def dart_str(s):
    return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("$", "\\$") + "'"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("engine_repo", help="transcribe.cpp checkout")
    ap.add_argument("ref", help="engine tag the package links, e.g. v0.3.1")
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()

    tag_date = datetime.fromisoformat(git(a.engine_repo, "log", "-1", "--format=%cI", a.ref).strip())
    names = [
        n
        for n in git(a.engine_repo, "ls-tree", "--name-only", a.ref, "catalog/").split()
        if n.endswith(".json") and not n.split("/")[-1].startswith("_")
    ]
    records = [json.loads(git(a.engine_repo, "show", f"{a.ref}:{n}")) for n in names]

    # Every family the engine's own catalogue names, transcribing or not. Used
    # to filter entries a developer or a remote catalogue adds; it uses the
    # catalogue's spelling, which is not always the engine's internal one.
    families = sorted({r["family"] for r in records})

    entries, late, skipped = [], [], []
    for r in sorted(records, key=lambda r: r["variant"]):
        if not r["capabilities"].get("transcribe", {}).get("supported"):
            continue
        repo = r.get("published_repo")
        if not repo:
            continue
        files = [d for d in r["downloads"] if d["size_bytes"] <= MAX_BYTES]
        if not files:
            continue
        info = hf(f"models/{repo}")
        sha = info["sha"]
        if datetime.fromisoformat(info["lastModified"].replace("Z", "+00:00")) > tag_date:
            late.append(f"{repo} ({info['lastModified']})")
        tree = {f["path"]: f for f in hf(f"models/{repo}/tree/{sha}")}
        kept = 0
        for d in files:
            f = tree.get(d["filename"])
            if "/" in d["filename"]:
                # A multi-file bundle, not the single .gguf the manager installs.
                skipped.append(f"{repo}/{d['filename']}: part of a multi-file bundle")
            elif f is None or "lfs" not in f:
                skipped.append(f"{repo}/{d['filename']}: not on Hugging Face")
            elif f["size"] != d["size_bytes"]:
                # Republished since the tag: a different file from the one the
                # catalogue describes, possibly from a newer converter.
                skipped.append(f"{repo}/{d['filename']}: {f['size']} bytes, catalogue says {d['size_bytes']}")
            else:
                entries.append((r, d, sha, f["lfs"]["oid"]))
                kept += 1
        print(f"{r['variant']}: {kept} file(s)", file=sys.stderr)

    out = [
        f"// GENERATED by tool/gen_catalog.py from transcribe.cpp {a.ref}. Do not edit.",
        "// ignore_for_file: lines_longer_than_80_chars",
        "",
        "part of 'catalog.dart';",
        "",
        f"const _engineRef = {dart_str(a.ref)};",
        "",
        "const _families = <String>{",
        *[f"  {dart_str(f)}," for f in families],
        "};",
        "",
        "List<ModelDescriptor> _bundled() => [",
    ]
    for r, d, sha, oid in entries:
        url = f"{HF}/{r['published_repo']}/resolve/{sha}/{d['filename']}"
        langs = ", ".join(dart_str(l) for l in r["languages"])
        out += [
            "  ModelDescriptor(",
            f"    id: ModelId({dart_str(d['filename'].removesuffix('.gguf'))}),",
            f"    variant: {dart_str(r['variant'])},",
            f"    quant: {dart_str(d['quant'])},",
            f"    family: {dart_str(r['family'])},",
            f"    displayName: {dart_str(r['display_name'])},",
            f"    languages: const [{langs}],",
            f"    license: {dart_str(r['license']['spdx'])},",
            f"    parameters: {r['params']},",
            f"    sizeBytes: {d['size_bytes']},",
            f"    sha256: {dart_str(oid)},",
            f"    url: Uri.parse({dart_str(url)}),",
            "  ),",
        ]
    out += ["];", ""]
    with open(a.out, "w") as fh:
        fh.write("\n".join(out))
    # Formatted here so a `dart format` over lib/ leaves the file alone.
    subprocess.run(["dart", "format", a.out], check=True, capture_output=True)

    variants = len({e[0]["variant"] for e in entries})
    print(f"{len(entries)} files across {variants} models -> {a.out}", file=sys.stderr)
    for l in skipped:
        print(f"skipped {l}", file=sys.stderr)
    if late:
        print(f"committed after {a.ref} ({tag_date}):", file=sys.stderr)
        for l in late:
            print(f"  {l}", file=sys.stderr)


main()
